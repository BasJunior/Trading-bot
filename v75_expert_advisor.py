class V75EAManager:
    """Manager class for V75 Expert Advisors"""
    
    def __init__(self):
        self.active_eas: Dict[int, V75ExpertAdvisor] = {}  # user_id -> EA
        self.ea_threads: Dict[int, threading.Thread] = {}
    
    def create_ea(self, user_id: int, user_api, config: V75Config = None) -> V75ExpertAdvisor:
        """Create a new V75 EA for a user"""
        if user_id in self.active_eas:
            # Stop existing EA first
            self.stop_ea(user_id)
        
        ea = V75ExpertAdvisor(user_id, user_api, config)
        self.active_eas[user_id] = ea
        return ea
    
    def get_ea(self, user_id: int) -> Optional[V75ExpertAdvisor]:
        """Get EA for a user"""
        return self.active_eas.get(user_id)
    
    def start_ea(self, user_id: int, start_balance: float = 0) -> bool:
        """Start the EA for a user"""
        ea = self.active_eas.get(user_id)
        if not ea:
            return False
        
        ea.is_active = True
        ea.stats.start_balance = start_balance
        ea.stats.current_balance = start_balance
        
        # Start monitoring thread
        thread = threading.Thread(
            target=self._run_ea_monitoring,
            args=(user_id,),
            daemon=True
        )
        thread.start()
        self.ea_threads[user_id] = thread
        
        logger.info(f"V75 EA started for user {user_id}")
        return True
    
    def stop_ea(self, user_id: int) -> bool:
        """Stop the EA for a user"""
        ea = self.active_eas.get(user_id)
        if not ea:
            return False
        
        ea.is_active = False
        
        # Remove from tracking
        if user_id in self.ea_threads:
            del self.ea_threads[user_id]
        if user_id in self.active_eas:
            del self.active_eas[user_id]
        
        logger.info(f"V75 EA stopped for user {user_id}")
        return True
    
    def _run_ea_monitoring(self, user_id: int):
        """Background thread for EA price monitoring and signal generation"""
        ea = self.active_eas.get(user_id)
        if not ea:
            return
        
        while ea.is_active:
            try:
                # Create event loop for this thread
                loop = asyncio.new_event_loop()
                asyncio.set_event_loop(loop)
                
                # Get current price
                loop.run_until_complete(self._update_ea_price(ea))
                
                # Check for trading signals if we have enough data
                if len(ea.price_history) >= ea.config.ema_slow_period:
                    call_signal = loop.run_until_complete(ea.should_buy_call())
                    put_signal = loop.run_until_complete(ea.should_buy_put())
                    
                    if call_signal:
                        loop.run_until_complete(
                            ea.place_trade("CALL", ea.config.lot_size)
                        )
                    elif put_signal:
                        loop.run_until_complete(
                            ea.place_trade("PUT", ea.config.lot_size)
                        )
                
                loop.close()
                
                # Sleep between checks
                time.sleep(5)
                
            except Exception as e:
                logger.error(f"EA monitoring error for user {user_id}: {e}")
                time.sleep(10)
    
    async def _update_ea_price(self, ea: V75ExpertAdvisor):
        """Update price data for an EA"""
        try:
            response = await ea.user_api.get_ticks(ea.SYMBOL)
            if "tick" in response:
                price = response["tick"].get("quote", 0)
                await ea.add_price(price)
        except Exception as e:
            logger.error(f"Price update error: {e}")
    
    def get_all_stats(self) -> Dict[int, dict]:
        """Get stats for all active EAs"""
        return {uid: ea.get_stats() for uid, ea in self.active_eas.items()}


